# 8. MAIN EXECUTION
# ============================================================

def run_execution():

    print()
    print(
        "=" * 60
    )

    print(
        "RecoverAI - Execution Layer"
    )

    print(
        "=" * 60
    )

    print(
        "Mode:",
        "RAZORPAY TEST MODE"
        if USE_RAZORPAY
        else "SYNTHETIC BATCH"
    )

    print()

    # --------------------------------------------------------
    # Check policy file
    # --------------------------------------------------------

    if not os.path.exists(
        POLICY_CSV
    ):

        raise FileNotFoundError(
            f"Policy file not found:\n"
            f"{POLICY_CSV}"
        )

    # --------------------------------------------------------
    # Check detection file
    # --------------------------------------------------------

    if not os.path.exists(
        DETECTION_CSV
    ):

        raise FileNotFoundError(
            f"Detection file not found:\n"
            f"{DETECTION_CSV}"
        )

    # --------------------------------------------------------
    # Load files
    # --------------------------------------------------------

    policy = pd.read_csv(
        POLICY_CSV
    )

    detection = pd.read_csv(
        DETECTION_CSV
    )

    print(
        f"Policy records: "
        f"{len(policy)}"
    )

    print(
        f"Detection records: "
        f"{len(detection)}"
    )

    # --------------------------------------------------------
    # Validate policy columns
    # --------------------------------------------------------

    required_policy_columns = [
        "payment_id",
        "action"
    ]

    for column in required_policy_columns:

        if column not in policy.columns:

            raise ValueError(
                f"Missing column in "
                f"policy_decisions.csv: "
                f"{column}"
            )

    # --------------------------------------------------------
    # Validate detection columns
    # --------------------------------------------------------

    required_detection_columns = [
        "payment_id",
        "amount"
    ]

    for column in required_detection_columns:

        if column not in detection.columns:

            raise ValueError(
                f"Missing column in detection CSV: "
                f"{column}"
            )

    # --------------------------------------------------------
    # Payment amount lookup
    # --------------------------------------------------------

    amounts = (
        detection
        .drop_duplicates(
            "payment_id"
        )
        .set_index(
            "payment_id"
        )[
            "amount"
        ]
        .to_dict()
    )

    # --------------------------------------------------------
    # Customer lookup
    # --------------------------------------------------------

    if "customer_id" in detection.columns:

        customers = (
            detection
            .drop_duplicates(
                "payment_id"
            )
            .set_index(
                "payment_id"
            )[
                "customer_id"
            ]
            .to_dict()
        )

    else:

        customers = {}

    # --------------------------------------------------------
    # Counters
    # --------------------------------------------------------

    results = {

        "sent": 0,

        "failed": 0,

        "skipped": 0
    }

    # ========================================================
    # PROCESS POLICY DECISIONS
    # ========================================================

    for _, row in policy.iterrows():

        payment_id = str(
            row["payment_id"]
        ).strip()

        action = str(
            row["action"]
        ).strip()

        # ----------------------------------------------------
        # Payment doesn't exist
        # ----------------------------------------------------

        if payment_id not in amounts:

            status = "failed"

            recovered = 0

            notes = (
                "Payment ID not found "
                "in detection data"
            )

        else:

            amount = amounts[
                payment_id
            ]

            customer_id = customers.get(
                payment_id,
                ""
            )

            # =================================================
            # RETRY NOW
            # =================================================

            if action == "retry_now":

                if USE_RAZORPAY:

                    (
                        status,
                        recovered,
                        notes
                    ) = attempt_retry_now(

                        payment_id,

                        amount,

                        customer_id
                    )

                    # Wait between API calls

                    time.sleep(
                        2
                    )

                else:

                    (
                        status,
                        recovered,
                        notes
                    ) = simulate_retry_now(

                        payment_id,

                        amount,

                        customer_id
                    )

            # =================================================
            # RETRY LATER
            # =================================================

            elif action == "retry_later":

                status = "skipped"

                recovered = 0

                notes = (
                    "retry_later not automated yet; "
                    "scheduler required"
                )

            # =================================================
            # SEND REMINDER
            # =================================================

            elif action == "send_reminder":

                status = "skipped"

                recovered = 0

                notes = (
                    "send_reminder not automated yet; "
                    "notification service required"
                )

            # =================================================
            # ESCALATE HUMAN
            # =================================================

            elif action == "escalate_human":

                status = "skipped"

                recovered = 0

                notes = (
                    "Escalated to human review"
                )

            # =================================================
            # UNKNOWN ACTION
            # =================================================

            else:

                status = "skipped"

                recovered = 0

                notes = (
                    f"Unknown action: "
                    f"{action}"
                )

        # ----------------------------------------------------
        # Audit logging
        # ----------------------------------------------------

        log_execution_outcome(

            payment_id,

            action,

            status,

            recovered_amount=recovered,

            notes=notes
        )

        results[
            status
        ] = results.get(
            status,
            0
        ) + 1

    # ========================================================
    # FINAL SUMMARY
    # ========================================================

    print()

    print(
        "=" * 60
    )

    print(
        "EXECUTION RUN COMPLETE"
    )

    print(
        "=" * 60
    )

    print(
        f"  sent:     "
        f"{results['sent']}"
    )

    print(
        f"  failed:   "
        f"{results['failed']}"
    )

    print(
        f"  skipped:  "
        f"{results['skipped']}"
    )

    print(
        "=" * 60
    )

    print()

    print(
        "Execution results logged."
    )

    print(
        "Run audit_metrics_layer.py "
        "to update metrics."
    )

    print()

    print(
        "IMPORTANT:"
    )

    print(
        "sent != recovered"
    )

    print(
        "Actual recovered money will be "
        "recorded by the Razorpay webhook "
        "after a successful payment."
    )


# ============================================================
# 9. START
# ============================================================

if __name__ == "__main__":

    run_execution()