# 6. REAL RAZORPAY PAYMENT LINK
# ============================================================

def attempt_retry_now(
    payment_id,
    amount,
    customer_id=""
):
    """
    Creates a real Razorpay Test Mode Payment Link.

    Returns:

        status
        recovered_amount
        notes

    IMPORTANT:

        Creating a Payment Link does NOT mean
        money has been recovered.
    """

    try:

        # ----------------------------------------------------
        # Validate payment ID
        # ----------------------------------------------------

        if pd.isna(payment_id):

            return (
                "failed",
                0,
                "Missing payment_id"
            )

        payment_id = str(
            payment_id
        ).strip()

        if not payment_id:

            return (
                "failed",
                0,
                "Empty payment_id"
            )

        # ----------------------------------------------------
        # Validate amount
        # ----------------------------------------------------

        if pd.isna(amount):

            return (
                "failed",
                0,
                "Amount is missing"
            )

        amount = float(
            amount
        )

        if amount <= 0:

            return (
                "failed",
                0,
                f"Invalid amount: {amount}"
            )

        # Razorpay uses paise

        amount_paise = int(
            round(
                amount * 100
            )
        )

        if amount_paise <= 0:

            return (
                "failed",
                0,
                "Amount in paise is zero"
            )

        # ----------------------------------------------------
        # Unique recovery reference
        # ----------------------------------------------------

        reference_id = (
            f"recovery_{payment_id}"
        )

        # ----------------------------------------------------
        # Payment Link data
        # ----------------------------------------------------

        payment_link_data = {

            "amount": amount_paise,

            "currency": "INR",

            "description": (
                f"Recovery for failed payment "
                f"{payment_id}"
            ),

            "reference_id": reference_id,

            "notes": {

                "original_payment_id":
                    payment_id
            }
        }

        if customer_id:

            payment_link_data[
                "notes"
            ][
                "customer_id"
            ] = str(
                customer_id
            )

        # ----------------------------------------------------
        # Razorpay API call
        # ----------------------------------------------------

        link = client.payment_link.create(
            payment_link_data
        )

        link_id = link.get(
            "id"
        )

        short_url = link.get(
            "short_url"
        )

        print()
        print(
            f"SUCCESS: {payment_id}"
        )

        print(
            f"Payment Link ID: {link_id}"
        )

        if short_url:

            print(
                f"Payment Link URL: {short_url}"
            )

        notes = (
            f"payment_link_id={link_id}; "
            f"payment_link_url={short_url}; "
            f"reference_id={reference_id}; "
            f"amount={amount}"
        )

        # Payment link created.
        # Customer has NOT paid yet.

        return (
            "sent",
            0,
            notes
        )

    except Exception as e:

        print()
        print(
            f"FAILED: {payment_id}"
        )

        print(
            f"Reason: {e}"
        )

        return (
            "failed",
            0,
            str(e)
        )


# ============================================================
# 7. SYNTHETIC EXECUTION
# ============================================================

def simulate_retry_now(
    payment_id,
    amount,
    customer_id=""
):
    """
    Simulates the recovery action for batch evaluation.

    This does NOT call Razorpay.

    It represents what the agent would execute
    in a production environment.
    """

    try:

        amount = float(
            amount
        )

    except Exception:

        return (
            "failed",
            0,
            "Invalid amount"
        )

    if amount <= 0:

        return (
            "failed",
            0,
            f"Invalid amount: {amount}"
        )

    notes = (
        "SIMULATED recovery action; "
        "Razorpay execution disabled "
        "for batch evaluation"
    )

    print(
        f"SIMULATED: {payment_id} "
        f"-> retry_now "
        f"-> ₹{amount:.2f}"
    )

    return (
        "sent",
        0,
        notes
    )


